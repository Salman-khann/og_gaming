import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const source = ts.transpileModule(readFileSync(new URL('../src/lib/api-input.ts', import.meta.url), 'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { jsonObject, integer, money, uuidField, sameOrigin } = await import('data:text/javascript;base64,' + Buffer.from(source).toString('base64'));
const request = body => new Request('https://og.test/api/matches', { method: 'POST', body });
for (const body of ['null', '[]', 'true', '42', '"text"', '{', '']) await assert.rejects(jsonObject(request(body)), error => error.status === 400);
assert.deepEqual(await jsonObject(request('{"action":"join"}')), { action: 'join' });
await assert.rejects(jsonObject(request(JSON.stringify({text:'x'.repeat(65536)}))),error=>error.status===413);
for (const value of [null, undefined, true, false, [], {}, '', '  ', Infinity, NaN, 1.5, -1]) assert.throws(() => integer(value, 0, 100));
assert.equal(integer('13', 0, 100), 13);
assert.equal(integer(0, 0, 100), 0);
for(const value of [true,false,null,[],{},'',NaN,Infinity,-1,10.001,100000000])assert.throws(()=>money(value));
assert.equal(money('1250.50'),1250.5);assert.equal(money(0),0);
assert.equal(uuidField('12345678-1234-1234-1234-123456789abc', 'match'), '12345678-1234-1234-1234-123456789abc');
for (const id of ['', null, 'not-a-uuid', '12345678-1234-1234-1234-123456789abz']) assert.throws(() => uuidField(id, 'match'));
sameOrigin(new Request('https://og.test/api', { headers: { origin: 'https://og.test' } }));
sameOrigin(new Request('https://og.test/api'));
for (const headers of [{ origin: 'https://evil.test' }, { origin: 'null' }, { 'sec-fetch-site': 'cross-site' }]) assert.throws(() => sameOrigin(new Request('https://og.test/api', { headers })), error => error.status === 403);
console.log('API regression tests passed: malformed bodies, integer coercion, invalid IDs and cross-site mutations rejected.');
